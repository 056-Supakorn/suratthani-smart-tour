import pandas as pd

# 1. โหลดข้อมูลจากไฟล์ของคุณ (เปลี่ยนชื่อไฟล์ให้ตรงกับที่โหลดมา)
file_path = "Real_data.csv"
df = pd.read_csv(file_path)

print(f"จำนวนข้อมูลก่อนคลีน: {len(df)} แถว")

# 2. ลบแถวที่มีข้อมูลว่างเปล่า (Null)
df = df.dropna()

# 3. สร้าง Dictionary สำหรับแก้คำผิด (Typo) ให้ตรงกับฐานข้อมูลเป๊ะๆ
# ด้านซ้ายคือ "คำที่มักพิมพ์ผิด" -> ด้านขวาคือ "ชื่อที่ถูกต้องในระบบ"
replace_dict = {
    "เขื่อนเชี่ยวหลาน": "เขื่อนรัชชประภา (เขาสามเกลอ)",
    "เขื่อนรัชชประภา": "เขื่อนรัชชประภา (เขาสามเกลอ)",
    "หมู่เกาะอ่างทอง": "อุทยานแห่งชาติหมู่เกาะอ่างทอง",
    "อ่างทอง": "อุทยานแห่งชาติหมู่เกาะอ่างทอง",
    "พระธาตุไชยา": "พระบรมธาตุไชยา",
    "วัดพระธาตุไชยา": "พระบรมธาตุไชยา",
    "ลักยิ้มริมน้ำ": "ร้านอาหารพื้นบ้าน ลักยิ้มริมน้ำ",
    "เกาะสมุย": "เกาะสมุย (หาดเฉวง)",
    "หาดเฉวง": "เกาะสมุย (หาดเฉวง)",
    "บ้านน้ำราด": "ป่าต้นน้ำ บ้านน้ำราด",
    "ป่าต้นน้ำ": "ป่าต้นน้ำ บ้านน้ำราด",
    "สวนโมกข์": "สวนโมกขพลาราม (วัดธารน้ำไหล)",
    "สวนโมก": "สวนโมกขพลาราม (วัดธารน้ำไหล)",
    "ชุมชนลีเล็ด": "ล่องเรือชม ชุมชนลีเล็ด",
    "ลีเล็ด": "ล่องเรือชม ชุมชนลีเล็ด",
    "คลองร้อยสาย": "วิถีชีวิต คลองร้อยสาย",
    "ลำภูคาเฟ่": "Lamphu Cafe (ลำภู คาเฟ่ริมน้ำ)",
    "Lamphu cafe": "Lamphu Cafe (ลำภู คาเฟ่ริมน้ำ)",
    "เขาสก": "อุทยานแห่งชาติเขาสก",
    "ตลาดศาลเจ้า": "ตลาดศาลเจ้า (สตรีทฟู้ดโต้รุ่ง)"
}

# แทนที่คำผิดในคอลัมน์ชื่อสถานที่ (สมมติว่าคอลัมน์ชื่อ 'place_name' ถ้าชื่ออื่นให้แก้ตรงนี้)
# ถ้าคอลัมน์ชื่อภาษาไทย เช่น 'สถานที่ที่เลือก' ให้เปลี่ยนคำว่า 'place_name' เป็นชื่อนั้นครับ
column_name = 'place_name' 

if column_name in df.columns:
    df[column_name] = df[column_name].replace(replace_dict)
    
    # แถม: ลบช่องว่างส่วนเกินหน้า-หลังตัวอักษร
    df[column_name] = df[column_name].astype(str).str.strip()

print(f"จำนวนข้อมูลหลังคลีน: {len(df)} แถว")

# 4. บันทึกเป็นไฟล์ใหม่ที่พร้อมใช้สอน AI ทันที
cleaned_file = "dataset.csv"
df.to_csv(cleaned_file, index=False, encoding='utf-8-sig')
print(f"✅ บันทึกไฟล์ที่คลีนแล้วสำเร็จในชื่อ: {cleaned_file}")